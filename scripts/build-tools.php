<?php
/**
 * Validates every tool definition and compiles the client-side engine.
 *
 * Usage: php scripts/build-tools.php
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$categories = [
    'mathematics', 'text', 'conversion', 'datetime', 'science',
    'finance', 'developer', 'education', 'everyday',
];

$inputTypes = ['number', 'text', 'textarea', 'select', 'checkbox', 'date', 'time', 'color'];
$requiredKeys = ['slug', 'name', 'category', 'description', 'icon', 'inputs', 'compute', 'tests'];

$files = glob($root . '/content/tools/*.php') ?: [];
sort($files);

$catalog = [];
$bodies = [];
$errors = [];
$seen = [];

foreach ($files as $file) {
    $definitions = require $file;
    if (!is_array($definitions)) {
        $errors[] = basename($file) . ': must return an array of tool definitions';
        continue;
    }

    foreach ($definitions as $i => $tool) {
        $where = basename($file) . '#' . ($i + 1) . (!empty($tool['slug']) ? ' (' . $tool['slug'] . ')' : '');

        foreach ($requiredKeys as $key) {
            if (!array_key_exists($key, $tool)) {
                $errors[] = "$where: missing key '$key'";
            }
        }
        if (!empty($errors) && !isset($tool['slug'])) {
            continue;
        }

        $slug = (string) ($tool['slug'] ?? '');
        if (!preg_match('/^[a-z0-9]+(?:-[a-z0-9]+)*$/', $slug)) {
            $errors[] = "$where: slug must be lowercase kebab-case";
            continue;
        }
        if (isset($seen[$slug])) {
            $errors[] = "$where: duplicate slug '$slug' (also in {$seen[$slug]})";
            continue;
        }
        $seen[$slug] = basename($file);

        if (!in_array($tool['category'] ?? '', $categories, true)) {
            $errors[] = "$where: unknown category '{$tool['category']}'";
        }
        if (strlen((string) ($tool['description'] ?? '')) > 160) {
            $errors[] = "$where: description longer than 160 characters";
        }
        if (!is_array($tool['inputs'] ?? null) || count($tool['inputs']) < 1 || count($tool['inputs']) > 8) {
            $errors[] = "$where: inputs must contain 1 to 8 fields";
            continue;
        }

        $names = [];
        foreach ($tool['inputs'] as $input) {
            $name = $input['name'] ?? '';
            $label = $input['label'] ?? '';
            $type = $input['type'] ?? '';
            if ($name === '' || $label === '') {
                $errors[] = "$where: every input needs a name and label";
                continue;
            }
            if (isset($names[$name])) {
                $errors[] = "$where: duplicate input name '$name'";
            }
            $names[$name] = true;
            if (!in_array($type, $inputTypes, true)) {
                $errors[] = "$where: input '$name' has unsupported type '$type'";
            }
            if ($type === 'select' && empty($input['options'])) {
                $errors[] = "$where: select input '$name' needs options";
            }
            if (!empty($input['showIf']) && !is_array($input['showIf'])) {
                $errors[] = "$where: showIf on '$name' must be an array";
            }
        }

        $tests = $tool['tests'] ?? [];
        if (!is_array($tests) || count($tests) < 2) {
            $errors[] = "$where: at least two test cases are required";
        } else {
            foreach ($tests as $t => $test) {
                if (!isset($test['input'], $test['expect']) || !is_array($test['expect']) || $test['expect'] === []) {
                    $errors[] = "$where: test " . ($t + 1) . " needs 'input' and a non-empty 'expect' map";
                }
            }
        }

        if (trim((string) ($tool['compute'] ?? '')) === '') {
            $errors[] = "$where: compute body is empty";
        }

        $entry = [
            'slug' => $slug,
            'name' => $tool['name'],
            'category' => $tool['category'],
            'description' => $tool['description'],
            'icon' => $tool['icon'],
            'featured' => (bool) ($tool['featured'] ?? false),
            'keywords' => array_values(array_map('strval', $tool['keywords'] ?? [])),
            'inputs' => $tool['inputs'],
            'tests' => $tool['tests'],
        ];
        $catalog[] = $entry;

        $body = rtrim((string) $tool['compute']);
        // Indent the compiled body inside the generated arrow function.
        $indented = preg_replace('/^/m', '      ', $body);
        $bodies[] = '  ' . json_encode($slug) . ": (v, h) => {\n" . $indented . "\n  },";
    }
}

if ($errors !== []) {
    fwrite(STDERR, "Tool build failed:\n - " . implode("\n - ", $errors) . "\n");
    exit(1);
}

usort($catalog, static fn (array $a, array $b): int => strcmp($a['slug'], $b['slug']));

$header = "// AUTO-GENERATED by scripts/build-tools.php — do not edit by hand.\n"
    . "// Run `php scripts/build-tools.php` after changing content/tools/*.php.\n\n";

$js = $header . "export const TOOLS = {\n" . implode("\n", $bodies) . "\n};\n\n"
    . 'export const TOOL_SLUGS = ' . json_encode(array_column($catalog, 'slug'), JSON_PRETTY_PRINT) . ";\n";

$json = json_encode($catalog, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";

$jsPath = $root . '/public/assets/js/tools.generated.js';
$jsonPath = $root . '/public/assets/data/tools.json';

if (!is_dir(dirname($jsPath))) {
    mkdir(dirname($jsPath), 0775, true);
}
if (!is_dir(dirname($jsonPath))) {
    mkdir(dirname($jsonPath), 0775, true);
}

file_put_contents($jsPath, $js);
file_put_contents($jsonPath, $json);

$counts = array_count_values(array_column($catalog, 'category'));
ksort($counts);
$summary = implode(', ', array_map(static fn ($c, $n) => "$c: $n", array_keys($counts), $counts));

echo "Built " . count($catalog) . " tools.\n";
echo "Categories — $summary\n";
echo "Wrote public/assets/js/tools.generated.js and public/assets/data/tools.json\n";
